const BLINK_SEQUENCE = [
    { frame: EYE_OPEN,   duration: 2800 },
    { frame: EYE_OPEN,   duration: 2200 },
    { frame: EYE_OPEN,   duration: 3500 },
    { frame: EYE_HALF,   duration: 80   },
    { frame: EYE_CLOSED, duration: 100  },
    { frame: EYE_HALF,   duration: 80   },
    { frame: EYE_OPEN,   duration: 3000 },
    { frame: EYE_OPEN,   duration: 1800 },
    { frame: EYE_HALF,   duration: 80   },
    { frame: EYE_CLOSED, duration: 100  },
    { frame: EYE_HALF,   duration: 80   },
    { frame: EYE_OPEN,   duration: 4000 },
]

export default function AsciiEye() {
    const [index, setIndex] = useState(0)

    useEffect(() => {
        const timer = setTimeout(() => {
            setIndex((i) => (i + 1) % BLINK_SEQUENCE.length)
        }, BLINK_SEQUENCE[index].duration)
        return () => clearTimeout(timer)
    }, [index])

    return (
        <pre
            style={{
                fontFamily: "ui-monospace, SFMono-Regular, Menlo, monospace",
                whiteSpace: "pre",
                lineHeight: "1.1",
                fontSize: "9px",
            }}
        >
            {BLINK_SEQUENCE[index].frame}
        </pre>
    )
}